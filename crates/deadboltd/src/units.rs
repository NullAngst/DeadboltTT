//! systemd units and the generated clamd config.

use deadbolt_common::paths;
use deadbolt_common::settings::Settings;
use std::time::Duration;
use tokio::process::Command;

pub const CLAMD: &str = "deadbolt-clamd.service";
pub const CLAMONACC: &str = "deadbolt-clamonacc.service";
pub const WORKER: &str = "deadbolt-worker.service";
pub const DISTRO_UNITS: &[&str] = &[
    "clamav-daemon.service",
    "clamav-clamonacc.service",
    "clamd@scan.service",
];
pub const FRESHCLAM: &[&str] = &["clamav-freshclam.service", "clamav-freshclam-once.service"];
pub const PROFILES: &[&str] = &["quick", "home", "full", "custom"];

pub async fn systemctl(args: &[&str]) -> Result<String, String> {
    let out = tokio::time::timeout(
        Duration::from_secs(60),
        Command::new("systemctl")
            .args(args)
            .stdin(std::process::Stdio::null())
            .output(),
    )
    .await
    .map_err(|_| format!("systemctl {} timed out", args.join(" ")))?
    .map_err(|e| format!("cannot run systemctl: {e}"))?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
    } else {
        Err(String::from_utf8_lossy(&out.stderr).trim().to_string())
    }
}

pub async fn is_active(unit: &str) -> bool {
    systemctl(&["is-active", "--quiet", unit]).await.is_ok()
}

pub async fn unit_state(unit: &str) -> String {
    match systemctl(&["is-enabled", unit]).await {
        Ok(s) => s,
        Err(e) => {
            if e.is_empty() {
                "disabled".into()
            } else {
                e.lines().last().unwrap_or("").to_string()
            }
        }
    }
}

pub async fn unit_exists(unit: &str) -> bool {
    matches!(
        systemctl(&["show", "--property=LoadState", "--value", unit])
            .await
            .as_deref(),
        Ok("loaded") | Ok("masked")
    )
}

/// Mask the distro's clamd units so two clamd processes don't each eat a gigabyte.
pub async fn take_over_clamd() -> Vec<String> {
    let mut log = Vec::new();
    for u in DISTRO_UNITS {
        if unit_exists(u).await && unit_state(u).await != "masked" {
            let _ = systemctl(&["stop", u]).await;
            match systemctl(&["mask", u]).await {
                Ok(_) => log.push(format!("masked {u}")),
                Err(e) => log.push(format!("could not mask {u}: {e}")),
            }
        }
    }
    log
}

/// true if a distro clamd unit is enabled or running again (an upgrade can do that).
pub async fn distro_units_back() -> bool {
    for u in DISTRO_UNITS {
        if unit_exists(u).await {
            let st = unit_state(u).await;
            if st != "masked" {
                return true;
            }
        }
    }
    false
}

pub async fn restart_freshclam() -> Result<String, String> {
    for u in FRESHCLAM {
        if unit_exists(u).await && unit_state(u).await != "masked" {
            return systemctl(&["restart", u])
                .await
                .map(|_| format!("restarted {u}"));
        }
    }
    // No unit: run freshclam once directly.
    let out = Command::new("freshclam")
        .arg("--quiet")
        .stdin(std::process::Stdio::null())
        .output()
        .await
        .map_err(|e| format!("cannot run freshclam: {e}"))?;
    if out.status.success() {
        Ok("freshclam finished".into())
    } else {
        Err(String::from_utf8_lossy(&out.stderr).trim().to_string())
    }
}

fn yn(b: bool) -> &'static str {
    if b { "yes" } else { "no" }
}

/// clamd.conf generated from deadbolt.toml. The header says hand edits are overwritten.
pub fn clamd_conf(s: &Settings, prevention: bool) -> String {
    let mut c = String::new();
    let mut line = |k: &str, v: &str| {
        c.push_str(k);
        c.push(' ');
        c.push_str(v);
        c.push('\n');
    };
    line(
        "#",
        "Generated by Deadbolt from /etc/deadbolt/deadbolt.toml.",
    );
    line(
        "#",
        "Hand edits to this file are overwritten. Change settings in Deadbolt instead.",
    );
    line("LocalSocket", paths::CLAMD_SOCK);
    line("LocalSocketGroup", "clamav");
    line("LocalSocketMode", "660");
    line("FixStaleSocket", "yes");
    line("LogSyslog", "yes");
    line("LogTime", "yes");
    line("DatabaseDirectory", "/var/lib/clamav");
    line("SelfCheck", "600");
    line("ConcurrentDatabaseReload", "yes");
    line("MaxThreads", &s.scan.max_threads.max(2).to_string());
    line("DetectPUA", yn(s.scan.detect_pua));
    line("MaxFileSize", &format!("{}M", s.scan.max_file_mb));
    line("MaxScanSize", &format!("{}M", s.scan.max_scan_mb));
    line("MaxRecursion", &s.scan.max_recursion.to_string());
    line("ScanArchive", yn(s.scan.scan_archive));
    line("AlertEncrypted", yn(s.scan.alert_encrypted));
    line("VirusEvent", paths::VIRUSEVENT_HOOK);
    for p in &s.realtime.include_paths {
        line("OnAccessIncludePath", p);
    }
    line("OnAccessExcludePath", paths::QUARANTINE_DIR);
    for p in &s.realtime.exclude_paths {
        line("OnAccessExcludePath", p);
    }
    line(
        "OnAccessPrevention",
        yn(prevention && s.realtime.prevention),
    );
    line("OnAccessExtraScanning", "yes");
    line("OnAccessExcludeRootUID", yn(s.realtime.exclude_root));
    line("OnAccessExcludeUname", paths::CLAMAV_USER);
    line("OnAccessExcludeUname", paths::WORKER_USER);
    line(
        "OnAccessMaxFileSize",
        &format!("{}M", s.realtime.max_file_mb),
    );
    c
}

/// Each schedule profile is a templated timer with a drop-in for its calendar.
pub fn timer_dropin(on_calendar: &str, skip_on_battery: bool) -> String {
    let mut s = format!(
        "# Written by Deadbolt.\n[Timer]\nOnCalendar=\nOnCalendar={on_calendar}\nPersistent=true\n"
    );
    if !skip_on_battery {
        s.push_str("\n[Service]\nEnvironment=DEADBOLT_SCAN_ON_BATTERY=1\n");
    }
    s
}

pub async fn apply_schedules(s: &Settings) -> Vec<String> {
    let mut log = Vec::new();
    for p in PROFILES {
        let timer = format!("deadbolt-scan@{p}.timer");
        let dir = format!("/etc/systemd/system/{timer}.d");
        match s.schedules.iter().find(|x| x.profile == *p && x.enabled) {
            Some(sch) => {
                if let Err(e) = std::fs::write(
                    format!("{dir}/schedule.conf"),
                    timer_dropin(&sch.on_calendar, sch.skip_on_battery),
                ) {
                    log.push(format!("cannot write {dir}: {e}"));
                    continue;
                }
                let _ = systemctl(&["daemon-reload"]).await;
                if let Err(e) = systemctl(&["enable", "--now", &timer]).await {
                    log.push(format!("cannot enable {timer}: {e}"));
                }
            }
            None => {
                let _ = std::fs::remove_file(format!("{dir}/schedule.conf"));
                let _ = systemctl(&["disable", "--now", &timer]).await;
            }
        }
    }
    log
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn conf_has_the_essentials() {
        let c = clamd_conf(&Settings::default(), true);
        assert!(c.contains("OnAccessExcludeUname clamav\nOnAccessExcludeUname deadbolt-worker\n"));
        assert!(c.contains("OnAccessPrevention yes"));
        assert!(c.contains("OnAccessExcludeRootUID no"));
        assert!(c.contains("OnAccessMaxFileSize 25M"));
        assert!(c.contains("OnAccessExcludePath /var/lib/deadbolt/quarantine"));
        assert!(c.contains("VirusEvent /usr/libexec/deadbolt/virusevent"));
        assert!(!c.contains("OnAccessIncludePath /\n"));
        let notify = clamd_conf(&Settings::default(), false);
        assert!(notify.contains("OnAccessPrevention no"));
    }

    #[test]
    fn dropin() {
        let d = timer_dropin("Sun *-*-* 03:00:00", true);
        assert!(d.contains("OnCalendar=\nOnCalendar=Sun *-*-* 03:00:00\n"));
        assert!(d.contains("Persistent=true"));
    }
}
